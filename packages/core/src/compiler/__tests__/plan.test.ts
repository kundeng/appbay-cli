// lcsTable — LCS DP table invariants
// ---------------------------------------------------------------------------

describe("lcsTable", () => {
  it("returns an all-zero table for two empty arrays", () => {
    const table = lcsTable([], []);
    // Should be a 1×1 matrix with only the 0-row and 0-col.
    expect(table).toHaveLength(1);
    expect(table[0]).toHaveLength(1);
    expect(table[0]![0]).toBe(0);
  });

  it("returns an all-zero table when arrays share no common elements", () => {
    const table = lcsTable(["a", "b", "c"], ["x", "y", "z"]);
    // LCS of fully disjoint arrays is 0.
    expect(table[3]![3]).toBe(0);
  });

  it("returns LCS length = array length for two identical arrays", () => {
    const arr = ["line1", "line2", "line3"];
    const table = lcsTable(arr, arr);
    // Diagonal fills up: table[m][n] should equal the array length.
    expect(table[3]![3]).toBe(3);
  });

  it("computes correct LCS length for a known pair", () => {
    // LCS("A", "B", "C", "D") vs ("B", "C", "D", "E") = 3 ("B","C","D")
    const a = ["A", "B", "C", "D"];
    const b = ["B", "C", "D", "E"];
    const table = lcsTable(a, b);
    expect(table[4]![4]).toBe(3);
  });

  it("produces a table with correct dimensions (m+1 × n+1)", () => {
    const a = ["x", "y"];
    const b = ["p", "q", "r"];
    const table = lcsTable(a, b);
    expect(table).toHaveLength(3); // m+1 = 3
    expect(table[0]).toHaveLength(4); // n+1 = 4
  });
});
