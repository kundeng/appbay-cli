describe("isPlainObject", () => {
  it("returns true for plain objects", () => {
    expect(isPlainObject({ a: 1 })).toBe(true);
    expect(isPlainObject({})).toBe(true);
  });

  it("returns false for arrays", () => {
    expect(isPlainObject([])).toBe(false);
  });

  it("returns false for null", () => {
    expect(isPlainObject(null)).toBe(false);
  });

  it("returns false for primitives", () => {
    expect(isPlainObject("string")).toBe(false);
    expect(isPlainObject(42)).toBe(false);
    expect(isPlainObject(undefined)).toBe(false);
  });
});

describe("mergeServiceFragment", () => {
  it("uses empty array when fragmentValue for APPEND_ARRAY_KEYS key is not an array", () => {
    // Covers the `Array.isArray(fragmentValue) ? fragmentValue : []` branch
    // when someone provides a non-array value for environment/volumes/ports.
    const base = { environment: ["BASE=1"] };
    // Cast to bypass TS — simulates a badly-shaped fragment at runtime.
    const frag = { environment: "BAD_STRING" as unknown as string[] };
    const result = mergeServiceFragment(base, frag);
    // Base array + empty fragment array → base unchanged (BAD_STRING discarded).
    expect(result.environment).toEqual(["BASE=1"]);
  });

  it("uses empty object when fragmentValue for MERGE_OBJECT_KEYS key is not a plain object", () => {
    // Covers the `isPlainObject(fragmentValue) ? fragmentValue : {}` branch.
    const base = { depends_on: { redis: { condition: "service_started" } } };
    const frag = { depends_on: null as unknown as Record<string, unknown> };
    const result = mergeServiceFragment(base, frag);
    // Base object + empty fragment object → base preserved.
    expect(result.depends_on).toEqual({ redis: { condition: "service_started" } });
  });

  it("recursively merges nested plain objects for non-special keys", () => {
    // Covers the `isPlainObject(baseValue) && isPlainObject(fragmentValue)` branch —
    // nested objects like `deploy.resources.limits` get deep-merged.
    const base = { deploy: { resources: { limits: { memory: "512m" } } } };
    const frag = { deploy: { resources: { limits: { cpus: "0.5" } } } };
    const result = mergeServiceFragment(base, frag as Record<string, unknown>);
    const limits = (result.deploy as Record<string, unknown>).resources as Record<string, unknown>;
    expect((limits.limits as Record<string, unknown>).memory).toBe("512m");
    expect((limits.limits as Record<string, unknown>).cpus).toBe("0.5");
  });
});

describe("mergeServicesInto", () => {
  it("starts from empty services when compose.services is not a plain object", () => {
    // Covers the `isPlainObject(compose.services) ? ... : {}` fallback.
    const compose = { services: null as unknown as Record<string, unknown> };
    const result = mergeServicesInto(compose, {
      web: { image: "nginx:latest" },
    });
    const svcs = result.services as Record<string, unknown>;
    expect(svcs.web).toEqual({ image: "nginx:latest" });
  });
});
